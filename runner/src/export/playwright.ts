import type { AppManifest, Assertion, HttpStep, Scenario, Step } from "@pr-agent/contracts";

// Exports a Scenario as a standalone Playwright test (P1 "export a scenario as .spec.ts").
// Runs against any build with the test hooks on: BASE_URL=http://localhost:3000 npx playwright test

const js = (v: unknown) => JSON.stringify(v);
const ind = (n: number) => " ".repeat(n);

/** Turns "$order.id" references into code that reads the saved response bodies. */
function value(v: unknown): string {
  if (typeof v === "string") {
    const whole = v.match(/^\$([A-Za-z_]\w*)((?:\.\w+)*)$/);
    if (whole) return `ref(${js(whole[1])}, ${js(whole[2]!.slice(1))})`;
    if (/\$[A-Za-z_]/.test(v)) return "`" + v.replace(/[`\\]/g, "\\$&").replace(/\$([A-Za-z_]\w*)((?:\.\w+)*)/g, (_, n, p) => `\${ref(${js(n)}, ${js(String(p).slice(1))})}`) + "`";
    return js(v);
  }
  if (Array.isArray(v)) return `[${v.map(value).join(", ")}]`;
  if (v && typeof v === "object") return `{ ${Object.entries(v).map(([k, x]) => `${js(k)}: ${value(x)}`).join(", ")} }`;
  return js(v);
}

function httpCall(s: HttpStep): string {
  const opts = [s.body !== undefined ? `data: ${value(s.body)}` : "", s.headers ? `headers: ${js(s.headers)}` : ""].filter(Boolean).join(", ");
  return `call(request, ${js(s.method)}, ${value(s.path)}${opts ? `, { ${opts} }` : ""})`;
}

function step(s: Step, m: AppManifest): string {
  const sel = (t: string) => js(m.selectors[t] ?? t);
  switch (s.op) {
    case "http":
      return s.saveAs ? `saved[${js(s.saveAs)}] = await ${httpCall(s)};` : `await ${httpCall(s)};`;
    case "parallel": {
      const all = `await Promise.all(Array.from({ length: ${s.count} }, () => ${httpCall(s.step)}))`;
      return s.step.saveAs ? `saved[${js(s.step.saveAs)}] = ${all};` : `${all};`;
    }
    case "ui":
      if (s.action === "goto") return `await page.goto(${value(s.target)});`;
      if (s.action === "fill") return `await page.locator(${sel(s.target)}).first().fill(${value(s.value ?? "")});`;
      return `await page.locator(${sel(s.target)}).first().${s.action}();`;
    case "wait":
      return `await page.waitForTimeout(${s.ms});`;
  }
}

function assertion(a: Assertion, m: AppManifest): string {
  switch (a.type) {
    case "db_count":
      return `expect((await db(request, ${js(a.table)}, ${value(a.where)})).count, ${js(a.id)}).toBe(${a.equals});`;
    case "http_status":
      return `for (const r of [saved[${js(a.ref)}]].flat()) expect(r.status, ${js(a.id)}).toBe(${a.equals});`;
    case "json_path":
      return `expect(path(bodyOf(saved[${js(a.ref)}]), ${js(a.path)}), ${js(a.id)}).toEqual(${value(a.equals)});`;
    case "ui_text":
      return `await expect(page.locator(${js(m.selectors[a.selector] ?? a.selector)}).first(), ${js(a.id)}).toContainText(${js(a.contains)}, { ignoreCase: true });`;
  }
}

export function toPlaywrightSpec(s: Scenario, manifest: AppManifest): string {
  const usesPage = s.steps.some((x) => x.op === "ui" || x.op === "wait") || s.assertions.some((a) => a.type === "ui_text");
  return `// ${s.id}: ${s.objective}
// ${s.rationale}
// Covers: ${s.sourceRefs.join(", ") || "-"}
// Generated by the PR Confidence runner. Needs the app's test hooks (ENABLE_TEST_HOOKS=1).
//   BASE_URL=http://localhost:3000 npx playwright test ${s.id}.spec.ts
import { expect, test, type APIRequestContext } from "@playwright/test";

const BASE_URL = process.env.BASE_URL ?? "http://localhost:3000";
test.use({ baseURL: BASE_URL });

type Saved = { status: number; body: any };
const saved: Record<string, Saved | Saved[]> = {};
const path = (v: any, p: string) => p.replace(/^\\$\\.?/, "").replace(/\\[(\\d+)\\]/g, ".$1").split(".").filter(Boolean).reduce((o, k) => o?.[k], v);
const bodyOf = (s: Saved | Saved[] | undefined) => (Array.isArray(s) ? s.map((x) => x.body) : s?.body);
const ref = (name: string, p: string) => {
  const s = saved[name];
  if (Array.isArray(s)) return p ? path(s[Number(p.split(".")[0])]?.body, p.split(".").slice(1).join(".")) : s.map((x) => x.body);
  return path(s?.body, p);
};
async function call(request: APIRequestContext, method: string, url: string, opts: { data?: unknown; headers?: Record<string, string> } = {}): Promise<Saved> {
  const res = await request.fetch(url, { method, ...opts });
  return { status: res.status(), body: await res.json().catch(() => null) };
}
async function db(request: APIRequestContext, table: string, where: Record<string, unknown>) {
  const qs = new URLSearchParams(Object.entries(where).map(([k, v]) => [k, String(v)]));
  return (await request.get(\`/__test/db/\${table}?\${qs}\`)).json();
}

test(${js(s.objective)}, async ({ ${usesPage ? "page, " : ""}request }) => {
${ind(2)}await request.post("/__test/seed", { data: { fixture: ${js(s.fixture)} } });
${ind(2)}await request.post("/__test/provider", { data: ${js({ mode: s.knobs?.provider ?? "ok", latencyMs: s.knobs?.latencyMs ?? 0 })} });

${s.steps.map((x) => ind(2) + step(x, manifest)).join("\n")}

${s.assertions.map((a) => ind(2) + assertion(a, manifest)).join("\n")}
});
`;
}
