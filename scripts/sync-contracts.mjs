// Copies packages/contracts/src into forge-app/src/contracts so the Forge app can use the same types
// without being part of the pnpm workspace. Run after any contracts change: pnpm sync:contracts
// --check exits 1 if the copy is stale (used in CI).
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const src = new URL("../packages/contracts/src/", import.meta.url).pathname;
const dest = new URL("../forge-app/src/contracts/", import.meta.url).pathname;
const header = "// GENERATED by scripts/sync-contracts.mjs from packages/contracts/src. Do not edit.\n";
const check = process.argv.includes("--check");

const files = readdirSync(src).filter((f) => f.endsWith(".ts"));
const want = new Map(files.map((f) => [f, header + readFileSync(join(src, f), "utf8")]));

if (check) {
  let have = [];
  try { have = readdirSync(dest).filter((f) => f.endsWith(".ts")); } catch {}
  const stale = [...want].filter(([f, body]) => {
    try { return readFileSync(join(dest, f), "utf8") !== body; } catch { return true; }
  }).map(([f]) => f);
  const extra = have.filter((f) => !want.has(f));
  if (stale.length || extra.length) {
    console.error(`forge-app/src/contracts is stale (${[...stale, ...extra].join(", ")}). Run: pnpm sync:contracts`);
    process.exit(1);
  }
  console.log("forge-app/src/contracts is up to date");
} else {
  rmSync(dest, { recursive: true, force: true });
  mkdirSync(dest, { recursive: true });
  for (const [f, body] of want) writeFileSync(join(dest, f), body);
  console.log(`synced ${want.size} files to forge-app/src/contracts`);
}
